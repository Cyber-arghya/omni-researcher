"""Markdown exporter with verified footnotes and frontmatter."""

from pathlib import Path

from src.config import settings
from src.security.sanitizer import sanitize_markdown_output
from src.state.schemas import ResearchReport


class MarkdownExporter:
    """Exports structured Markdown dossiers."""

    def export(self, report: ResearchReport, output_dir: Path | None = None) -> Path:
        """Save report to a timestamped Markdown file."""
        target_dir = output_dir or settings.reports_dir
        target_dir.mkdir(parents=True, exist_ok=True)

        sanitized_topic = "".join(c if c.isalnum() else "_" for c in report.topic)[:50]
        timestamp = report.generated_at.strftime("%Y%m%d_%H%M%S")
        file_path = target_dir / f"research_{timestamp}_{sanitized_topic}.md"

        content = (
            report.chapters[0]["content_markdown"] if report.chapters else report.executive_summary
        )
        sanitized_content = sanitize_markdown_output(content)

        header = (
            f"# {report.title}\n\n"
            f"> **Generated by OpenDeepResearcher** | Model: `{report.model_used}` | Sources: {report.total_sources_consulted}\n"
            f"> Date: {report.generated_at.strftime('%B %d, %Y')}\n\n"
            f"---\n\n"
        )

        full_doc = header + sanitized_content
        file_path.write_text(full_doc, encoding="utf-8")
        return file_path
